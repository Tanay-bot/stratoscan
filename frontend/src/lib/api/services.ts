const demoLatency = () => delay(450 + Math.random() * 550)

/**
 * Validate a real-API payload against its zod schema.
 *
 * ``unwrap`` already normalized HTTP errors; this layer catches CONTRACT
 * drift — the backend returning a shape that no longer matches types.ts.
 * A mismatch throws a clear, user-safe error instead of rendering undefined
 * fields. Demo-mode payloads are generated by the same typed fakes, so they
 * skip validation (they cannot drift from the code that ships them).
 */
function validate<T>(schema: import('zod').ZodTypeAny, data: unknown): T {
  // T (the app type) and the zod schema are maintained in parallel — the
  // schema is the runtime source of truth, T is the compile-time shape. The
  // loose param/cast is deliberate: it lets the schema accept the response
  // as `unknown` and validate at runtime without demanding the two types be
  // structurally identical (which .passthrough() schemas can't guarantee).
  const parsed = schema.safeParse(data)
  if (!parsed.success) {
    const first = parsed.error.issues[0]
    const where = first ? ` at ${first.path.join('.') || 'root'}` : ''
    console.error('[api-contract] Response failed validation', parsed.error.issues)
    throw new Error(
      `The Stratoscan API returned an unexpected response${where}. ` +
        'Please refresh and try again — if this persists, the backend may be out of date.',
    )
  }
  return parsed.data as T
}

// ── Auth ────────────────────────────────────────────────────────────────────

export async function login(payload: LoginRequest): Promise<AuthResponse> {
  if (DEMO_MODE) {
    await demoLatency()
    const demo = demoLogin(payload.email, payload.password)
    return {
      access_token: demo.access_token,
      token_type: 'bearer',
      expires_in: 604800,
      user: demo.user,
      email_sent: true,
    }
  }
  return validate(authResponseSchema, await unwrap<AuthResponse>(api.post('/auth/login', payload)))
}

