/**
 * Move this browser's trial backtests and share links into the account that
 * just signed in. Clears the trial token only once the server confirms, so a
 * failed claim can be retried on the next sign-in. Never throws.
 */
export async function claimTrialWork(): Promise<{
  claimed_backtests: number
  claimed_shares: number
} | null> {
  if (DEMO_MODE || getToken() === null || getTrialToken() === null) return null
  try {
    const res = await unwrap<{ claimed_backtests: number; claimed_shares: number }>(
      api.post('/try/claim', null, { headers: trialHeaders() }),
    )
    clearTrialToken()
    return res
  } catch {
    return null
  }
}

/** Download simulated trades as a CSV (POST /backtest/export). */
export async function exportBacktestCsv(req: BacktestRequest): Promise<Blob> {
  if (DEMO_MODE) {
    await demoLatency()
    const demo = demoBacktest(req)
    const lines = [
      'symbol,side,buy_date,buy_price,sell_date,sell_price,shares,pnl,pnl_pct,exit_reason',
    ]
    for (const r of Object.values(demo.results)) {
      for (const t of r.trades) {
        lines.push(
          [
            t.symbol,
            t.side,
            t.buy_date,
            t.buy_price,
            t.sell_date ?? '',
            t.sell_price ?? '',
            t.shares,
            t.pnl ?? '',
            t.pnl_pct ?? '',
            t.exit_reason,
          ].join(','),
        )
      }
    }
    return new Blob([lines.join('\n')], { type: 'text/csv' })
  }
  return unwrap<Blob>(
    api.post('/backtest/export', req, { responseType: 'blob', timeout: LONG_TIMEOUT_MS }),
  )
}

/** Download screening results as a CSV (POST /screen/export). */
export async function exportScreenCsv(req: ScreenRequest): Promise<Blob> {
  if (DEMO_MODE) {
    await demoLatency()
    const demo = demoScreen(req)
    const lines = [
      'symbol,company_name,sector,current_price,price_change_pct,market_cap,pe_ratio,rsi_14,volume,score',
    ]
    for (const s of demo.results) {
      lines.push(
        [
          s.symbol,
          `"${String(s.company_name ?? '').replaceAll('"', '""')}"`,
          s.sector ?? '',
          s.current_price ?? '',
          s.price_change_pct ?? '',
          s.market_cap ?? '',
          s.pe_ratio ?? '',
          s.rsi_14 ?? '',
          s.volume ?? '',
          s.score ?? '',
        ].join(','),
      )
    }
    return new Blob([lines.join('\n')], { type: 'text/csv' })
  }
  return unwrap<Blob>(
    api.post('/screen/export', req, { responseType: 'blob', timeout: LONG_TIMEOUT_MS }),
  )
}

/** Trigger a browser download of a Blob (CSV exports, Tier 3). */
export function downloadBlob(blob: Blob, filename: string): void {
  const url = URL.createObjectURL(blob)
  const a = document.createElement('a')
  a.href = url
  a.download = filename
  document.body.appendChild(a)
  a.click()
  a.remove()
  URL.revokeObjectURL(url)
}

